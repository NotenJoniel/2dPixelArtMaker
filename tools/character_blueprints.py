def get_size_spec(size_id: str) -> dict[str, Any]:
    if size_id not in SIZE_PRESETS:
        valid = ", ".join(SIZE_PRESETS.keys())
        raise KeyError(f"Unknown size_preset {size_id!r}. Valid options: {valid}")
    return SIZE_PRESETS[size_id]


def get_scale_spec(size_id: str, scale_id: str = "M") -> dict[str, Any]:
    get_size_spec(size_id)
    sc = scale_id.upper()
    if sc not in SIZE_CLASS_SPECS[size_id]:
        valid = ", ".join(SIZE_CLASS_SPECS[size_id].keys())
        raise KeyError(f"Unknown scale {scale_id!r}. Valid options: {valid}")
    return SIZE_CLASS_SPECS[size_id][sc]


def get_role_spec(role_id: str = "hero") -> dict[str, Any]:
    r = role_id.lower()
    if r not in ROLE_TIERS:
        valid = ", ".join(ROLE_TIERS.keys())
        raise KeyError(f"Unknown role {role_id!r}. Valid options: {valid}")
    return ROLE_TIERS[r]


def get_taste_spec(taste_id: str) -> dict[str, Any]:
    if taste_id not in TASTE_PRESETS:
        valid = ", ".join(TASTE_PRESETS.keys())
        raise KeyError(f"Unknown taste_preset {taste_id!r}. Valid options: {valid}")
    return TASTE_PRESETS[taste_id]


def apply_ascii_overlay(base_grid: str, overlay_grid: str) -> str:
    """base_grid の上に overlay_grid の非 '.' 文字を重ね合わせた ASCII マップを返す。"""
    base_rows = [list(r) for r in textwrap.dedent(base_grid).strip("\n").splitlines()]
    over_rows = textwrap.dedent(overlay_grid).strip("\n").splitlines()
    if len(base_rows) != len(over_rows):
        raise ValueError(f"Overlay row count {len(over_rows)} != base row count {len(base_rows)}")
    for y, o_row in enumerate(over_rows):
        if len(o_row) != len(base_rows[y]):
            raise ValueError(f"Overlay width {len(o_row)} != base width {len(base_rows[y])} at row {y}")
        for x, ch in enumerate(o_row):
            if ch != ".":
                base_rows[y][x] = ch
    return "\n".join("".join(r) for r in base_rows)


def get_mannequin(size_id: str, direction: str = "down", *, role: str = "hero") -> str:
    """
    武器・帽子・外ハネ髪を含まないクリーンな素体マネキン ASCII マップを返す。
    頭部が肌色で塗りつぶされているため、上から髪型や帽子を自由に重ねても額に透過穴が空かない。
    role='mob' 指定時は白目(W)を肌色(s)へ自動置換し、モブ用のシンプルな黒目にする。
    """
    spec = get_size_spec(size_id)
    get_role_spec(role)
    if direction not in ("down", "up", "right", "left"):
        raise KeyError(f"Unknown direction {direction!r}. Expected down / up / right / left.")

    raw = MANNEQUINS.get((size_id, direction)) or MANNEQUINS.get((size_id, "down"))
    if raw is None:
        raise KeyError(f"No mannequin found for size_preset={size_id!r}")

    lines = [list(r) for r in textwrap.dedent(raw).strip("\n").splitlines()]
    if role.lower() == "mob" and size_id != "fc_16x16":
        head_limit_y = int(spec["default_origin"][1] * 0.56)
        for y in range(min(len(lines), head_limit_y + 1)):
            for x, ch in enumerate(lines[y]):
                if ch == "W":
                    lines[y][x] = "s"
    return "\n".join("".join(r) for r in lines)


def get_equipment_overlay(size_id: str, equip_id: str = "back_sword_45", direction: str = "down") -> str:
    """分離済みの装備オーバーレイ ASCII マップを返す（該当方向が未収録の場合は全透明 '.' マップを返す）。"""
    spec = get_size_spec(size_id)
    if direction not in ("down", "up", "right", "left"):
        raise KeyError(f"Unknown direction {direction!r}. Expected down / up / right / left.")
    key = (size_id, equip_id, direction)
    if key in EQUIPMENT_OVERLAYS:
        return textwrap.dedent(EQUIPMENT_OVERLAYS[key]).strip("\n")
    cw, ch = spec["canvas_size"]
    return "\n".join("." * cw for _ in range(ch))


def resolve_blueprint(
    size_id: str,
    taste_id: str,
    direction: str = "down",
    *,
    equipped: bool = False,
) -> tuple[str, tuple[str, str, str], bool]:
    """
    指定された (size_id, taste_id, direction) の素体マップを返す。
    デフォルト (equipped=False) は「武器なし」のクリーン構造を返し、仲間や街人への武器混入を防ぐ。
    equipped=True 指定時は検証済みの斜め45度背負い剣オーバーレイを合成して返す。
    完全一致が未収録でも、同一 size_id 内の基準テイスト素体へ安全にフォールバックし、
    (grid_str, resolved_key, is_exact) を返す。
    """
    get_size_spec(size_id)
    get_taste_spec(taste_id)
    if direction not in ("down", "up", "right", "left"):
        raise KeyError(f"Unknown direction {direction!r}. Expected down / up / right / left.")

    resolved_grid: str | None = None
    resolved_key: tuple[str, str, str] | None = None
    is_exact = False

    exact_key = (size_id, taste_id, direction)
    if exact_key in BLUEPRINTS:
        resolved_grid = textwrap.dedent(BLUEPRINTS[exact_key]).strip("\n")
        resolved_key = exact_key
        is_exact = True

    if resolved_grid is None:
        # 1. 同一 size_id × 同一 direction のフォールバックテイストを探す
        for fb_taste in _FALLBACK_TASTES.get(size_id, ()):
            fb_key = (size_id, fb_taste, direction)
            if fb_key in BLUEPRINTS:
                resolved_grid = textwrap.dedent(BLUEPRINTS[fb_key]).strip("\n")
                resolved_key = fb_key
                break

    if resolved_grid is None:
        # 2. 同一 size_id × taste_id の down を探す
        down_same_taste = (size_id, taste_id, "down")
        if down_same_taste in BLUEPRINTS:
            resolved_grid = textwrap.dedent(BLUEPRINTS[down_same_taste]).strip("\n")
            resolved_key = down_same_taste

    if resolved_grid is None:
        # 3. 同一 size_id の基準 down を返す
        for fb_taste in _FALLBACK_TASTES.get(size_id, ()):
            fb_key = (size_id, fb_taste, "down")
            if fb_key in BLUEPRINTS:
                resolved_grid = textwrap.dedent(BLUEPRINTS[fb_key]).strip("\n")
                resolved_key = fb_key
                break

    if resolved_grid is None or resolved_key is None:
        raise KeyError(f"No blueprint found for size_preset={size_id!r}")

    if equipped:
        rs, rt, rd = resolved_key
        if rt == "cool" and (rs, "back_sword_45", rd) in EQUIPMENT_OVERLAYS:
            resolved_grid = apply_ascii_overlay(resolved_grid, EQUIPMENT_OVERLAYS[(rs, "back_sword_45", rd)])

    return resolved_grid, resolved_key, is_exact


def get_blueprint(size_id: str, taste_id: str, direction: str = "down", *, equipped: bool = False) -> str:
    bp, _, _ = resolve_blueprint(size_id, taste_id, direction, equipped=equipped)
    return bp


def _verify_single_grid(label: str, size_id: str, raw: str, valid_chars: set[str], check_height: bool = True) -> tuple[list[str], int | None]:
    errs: list[str] = []
    spec = get_size_spec(size_id)
    cw, ch = spec["canvas_size"]
    exp_ground_y = spec["default_origin"][1] - 1
    lines = textwrap.dedent(raw).strip("\n").splitlines()
    if len(lines) != ch:
        errs.append(f"{label}: expected {ch} rows, got {len(lines)}")
    ys: list[int] = []
    for r_i, row in enumerate(lines):
        if len(row) != cw:
            errs.append(f"{label} row {r_i}: expected width {cw}, got {len(row)}")
        bad = set(row) - valid_chars
        if bad:
            errs.append(f"{label} row {r_i}: unknown symbols {sorted(bad)}")
        if any(ch_c != "." for ch_c in row):
            ys.append(r_i)
    if not ys:
        errs.append(f"{label}: grid is empty")
        return errs, None
    min_y, max_y = min(ys), max(ys)
    if check_height:
        bh = max_y - min_y + 1
        lo_h, hi_h = spec["body_height_range"]
        if not (lo_h <= bh <= hi_h):
            errs.append(f"{label}: height {bh}px (y={min_y}..{max_y}) outside {lo_h}..{hi_h}px")
        if max_y != exp_ground_y:
            errs.append(f"{label}: bottom y={max_y} does not match ground_y={exp_ground_y} (origin={spec['default_origin']})")
    return errs, max_y


def verify_all_blueprints() -> list[str]:
    """全収録マネキン・素体・装備オーバーレイの寸法・文字種・実身長・接地ライン一致を機械検証する。"""
    errors: list[str] = []
    valid_chars = set(STANDARD_SYMBOL_MAP.keys()) | {"."}
    ground_by_pair: dict[tuple[str, str], dict[str, int]] = {}

    # 1. マネキン素体の検証
    for (size_id, direction), raw in MANNEQUINS.items():
        e_list, _ = _verify_single_grid(f"mannequin:{size_id}/{direction}", size_id, raw, valid_chars, check_height=True)
        errors.extend(e_list)

    # 2. スタイル別素体の検証
    for (size_id, taste_id, direction), raw in BLUEPRINTS.items():
        e_list, max_y = _verify_single_grid(f"blueprint:{size_id}/{taste_id}/{direction}", size_id, raw, valid_chars, check_height=True)
        errors.extend(e_list)
        if max_y is not None:
            ground_by_pair.setdefault((size_id, taste_id), {})[direction] = max_y

    for (size_id, taste_id), dir_map in ground_by_pair.items():
        if len(set(dir_map.values())) > 1:
            errors.append(f"{size_id}/{taste_id}: inconsistent ground y across directions: {dir_map}")

    # 3. 装備オーバーレイ単体および合成後の検証
    for (size_id, equip_id, direction), raw in EQUIPMENT_OVERLAYS.items():
        e_list, _ = _verify_single_grid(f"overlay:{size_id}/{equip_id}/{direction}", size_id, raw, valid_chars, check_height=False)
        errors.extend(e_list)
        comp = get_blueprint(size_id, "cool", direction, equipped=True)
        e_comp, _ = _verify_single_grid(f"equipped:{size_id}/cool/{direction}", size_id, comp, valid_chars, check_height=True)
        errors.extend(e_comp)

    # 4. 全 4x4x4 組み合わせで resolve_blueprint / get_mannequin が例外を出さないことも保証
    for s_id in SIZE_PRESETS:
        for d_id in ("down", "up", "right", "left"):
            mq = get_mannequin(s_id, d_id, role="mob")
            if not mq:
                errors.append(f"get_mannequin failed for {s_id}/{d_id}")
            for t_id in TASTE_PRESETS:
                bp, _, _ = resolve_blueprint(s_id, t_id, d_id, equipped=False)
                if not bp:
                    errors.append(f"resolve_blueprint failed for {s_id}/{t_id}/{d_id}")

    return errors


