def get_size_spec(size_id: str) -> dict[str, Any]:
    if size_id not in SIZE_PRESETS:
        valid = ", ".join(SIZE_PRESETS.keys())
        raise KeyError(f"Unknown size_preset {size_id!r}. Valid options: {valid}")
    return SIZE_PRESETS[size_id]


def get_scale_spec(size_id: str, scale_id: str = "M") -> dict[str, Any]:
    get_size_spec(size_id)
    sc = scale_id.upper()
    if sc not in SIZE_CLASS_SPECS[size_id]:
        valid = ", ".join(SIZE_CLASS_SPECS[size_id].keys())
        raise KeyError(f"Unknown scale {scale_id!r}. Valid options: {valid}")
    return SIZE_CLASS_SPECS[size_id][sc]


def get_role_spec(role_id: str = "hero") -> dict[str, Any]:
    r = role_id.lower()
    if r not in ROLE_TIERS:
        valid = ", ".join(ROLE_TIERS.keys())
        raise KeyError(f"Unknown role {role_id!r}. Valid options: {valid}")
    return ROLE_TIERS[r]


def get_taste_spec(taste_id: str) -> dict[str, Any]:
    if taste_id not in TASTE_PRESETS:
        valid = ", ".join(TASTE_PRESETS.keys())
        raise KeyError(f"Unknown taste_preset {taste_id!r}. Valid options: {valid}")
    return TASTE_PRESETS[taste_id]


def resolve_blueprint(size_id: str, taste_id: str, direction: str = "down") -> tuple[str, tuple[str, str, str], bool]:
    """
    指定された (size_id, taste_id, direction) の素体マップを返す。
    完全一致が未収録でも、同一 size_id 内の基準テイスト素体へ安全にフォールバックし、
    (grid_str, resolved_key, is_exact) を返す。
    """
    get_size_spec(size_id)
    get_taste_spec(taste_id)
    if direction not in ("down", "up", "right", "left"):
        raise KeyError(f"Unknown direction {direction!r}. Expected down / up / right / left.")

    exact_key = (size_id, taste_id, direction)
    if exact_key in BLUEPRINTS:
        return textwrap.dedent(BLUEPRINTS[exact_key]).strip("\n"), exact_key, True

    # 1. 同一 size_id × 同一 direction のフォールバックテイストを探す
    for fb_taste in _FALLBACK_TASTES.get(size_id, ()):
        fb_key = (size_id, fb_taste, direction)
        if fb_key in BLUEPRINTS:
            return textwrap.dedent(BLUEPRINTS[fb_key]).strip("\n"), fb_key, False

    # 2. 同一 size_id × taste_id の down を探す
    down_same_taste = (size_id, taste_id, "down")
    if down_same_taste in BLUEPRINTS:
        return textwrap.dedent(BLUEPRINTS[down_same_taste]).strip("\n"), down_same_taste, False

    # 3. 同一 size_id の基準 down を返す
    for fb_taste in _FALLBACK_TASTES.get(size_id, ()):
        fb_key = (size_id, fb_taste, "down")
        if fb_key in BLUEPRINTS:
            return textwrap.dedent(BLUEPRINTS[fb_key]).strip("\n"), fb_key, False

    raise KeyError(f"No blueprint found for size_preset={size_id!r}")


def get_blueprint(size_id: str, taste_id: str, direction: str = "down") -> str:
    bp, _, _ = resolve_blueprint(size_id, taste_id, direction)
    return bp


def verify_all_blueprints() -> list[str]:
    """全収録素体のキャンバス寸法・文字種・実身長・4方向接地ライン一致を機械検証する。"""
    errors: list[str] = []
    valid_chars = set(STANDARD_SYMBOL_MAP.keys()) | {"."}
    ground_by_pair: dict[tuple[str, str], dict[str, int]] = {}

    for (size_id, taste_id, direction), raw in BLUEPRINTS.items():
        spec = get_size_spec(size_id)
        cw, ch = spec["canvas_size"]
        exp_ground_y = spec["default_origin"][1] - 1
        lines = textwrap.dedent(raw).strip("\n").splitlines()
        if len(lines) != ch:
            errors.append(f"{size_id}/{taste_id}/{direction}: expected {ch} rows, got {len(lines)}")
        ys: list[int] = []
        for r_i, row in enumerate(lines):
            if len(row) != cw:
                errors.append(f"{size_id}/{taste_id}/{direction} row {r_i}: expected width {cw}, got {len(row)}")
            bad = set(row) - valid_chars
            if bad:
                errors.append(f"{size_id}/{taste_id}/{direction} row {r_i}: unknown symbols {sorted(bad)}")
            if any(ch_c != "." for ch_c in row):
                ys.append(r_i)
        if not ys:
            errors.append(f"{size_id}/{taste_id}/{direction}: blueprint is empty")
            continue
        min_y, max_y = min(ys), max(ys)
        bh = max_y - min_y + 1
        lo_h, hi_h = spec["body_height_range"]
        if not (lo_h <= bh <= hi_h):
            errors.append(
                f"{size_id}/{taste_id}/{direction}: height {bh}px (y={min_y}..{max_y}) outside {lo_h}..{hi_h}px"
            )
        if max_y != exp_ground_y:
            errors.append(
                f"{size_id}/{taste_id}/{direction}: bottom y={max_y} does not match ground_y={exp_ground_y} (origin={spec['default_origin']})"
            )
        ground_by_pair.setdefault((size_id, taste_id), {})[direction] = max_y

    for (size_id, taste_id), dir_map in ground_by_pair.items():
        if len(set(dir_map.values())) > 1:
            errors.append(f"{size_id}/{taste_id}: inconsistent ground y across directions: {dir_map}")

    # 全 4x4x4 組み合わせで resolve_blueprint が例外を出さないことも保証
    for s_id in SIZE_PRESETS:
        for t_id in TASTE_PRESETS:
            for d_id in ("down", "up", "right", "left"):
                bp, _, _ = resolve_blueprint(s_id, t_id, d_id)
                if not bp:
                    errors.append(f"resolve_blueprint failed for {s_id}/{t_id}/{d_id}")

    return errors


def main() -> int:
    parser = argparse.ArgumentParser(description="サイズ規格 × テイスト × サイズ区分 × 役割ランク別の素体ブループリント参照ツール")
    parser.add_argument("--list", action="store_true", help="利用可能なサイズ規格・サイズ区分・役割ランク・テイスト・素体一覧を表示")
    parser.add_argument("--info", nargs=2, metavar=("SIZE_ID", "TASTE_ID"), help="指定したサイズ×テイストの定量仕様を表示")
    parser.add_argument("--scale", default="M", help="--info 時のサイズ区分 (S / M / L / XL, default: M)")
    parser.add_argument("--role", default="hero", help="--info 時の役割ランク (hero / party / mob / enemy / midboss / boss, default: hero)")
    parser.add_argument("--show", nargs=3, metavar=("SIZE_ID", "TASTE_ID", "DIR"), help="指定した素体ASCIIマップを表示（未収録組合せは同サイズの基準構造へ安全にフォールバック）")
    parser.add_argument("--verify", action="store_true", help="全収録ブループリントの行数・列幅・接地ライン・実身長整合性を検証")
    args = parser.parse_args()

    if args.verify:
        errs = verify_all_blueprints()
        if errs:
            for e in errs:
                print(f"[VERIFY ERROR] {e}", file=sys.stderr)
            return 1
        print(f"[VERIFY PASS] All {len(BLUEPRINTS)} blueprints and 64 preset combinations verified cleanly.")
        return 0

    if args.list:
        print("=== Size Presets (Base M-size) ===")
        for k, v in SIZE_PRESETS.items():
            print(f"  - {k:12s}: {v['label']} (canvas={v['canvas_size']}, origin={v['default_origin']}, body_h={v['body_height_range']}px)")
        print("\n=== Size Classes (--scale) ===")
        for sc in ("S", "M", "L", "XL"):
            print(f"  - {sc:4s}: {SIZE_CLASS_SPECS['sfc_16x24'][sc]['label']}")
        print("\n=== Role Tiers (--role) ===")
        for r_k, r_v in ROLE_TIERS.items():
            print(f"  - {r_k:10s}: {r_v['label']} (recommended scales: {', '.join(r_v['recommended_scales'])})")
        print("\n=== Taste Presets ===")
        for k, v in TASTE_PRESETS.items():
            print(f"  - {k:14s}: {v['label']}")
        print("\n=== Explicitly Verified Blueprints (other combinations auto-fallback safely) ===")
        for s, t, d in BLUEPRINTS:
            print(f"  - {s} / {t} / {d}")
        return 0

    if args.info:
        s_id, t_id = args.info
        out = {
            "size_preset": {s_id: get_size_spec(s_id)},
            "scale_class": {args.scale.upper(): get_scale_spec(s_id, args.scale)},
            "role_tier": {args.role.lower(): get_role_spec(args.role)},
            "taste_preset": {t_id: get_taste_spec(t_id)},
        }
        print(json.dumps(out, ensure_ascii=False, indent=2))
        return 0

    if args.show:
        s_id, t_id, d_id = args.show
        bp, resolved_key, is_exact = resolve_blueprint(s_id, t_id, d_id)
        lines = bp.splitlines()
        spec = get_size_spec(s_id)
        if is_exact:
            print(f"# Blueprint: {s_id} x {t_id} ({d_id}) — {len(lines[0])}x{len(lines)} px, origin={list(spec['default_origin'])}")
        else:
            rs, rt, rd = resolved_key
            print(
                f"# Blueprint (Structural Base Fallback -> {rs} x {rt} [{rd}]): "
                f"requested={s_id} x {t_id} ({d_id}) — {len(lines[0])}x{len(lines)} px, origin={list(spec['default_origin'])}"
            )
            print(f"# Note: Keep this exact head:torso:legs proportion & ground_y={spec['default_origin'][1]-1}, and apply '{t_id}' taste rules from --info.")
        print(bp)
        return 0

    parser.print_help()
    return 0


if __name__ == "__main__":
    sys.exit(main())
