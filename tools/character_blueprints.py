def get_size_spec(size_id: str) -> dict[str, Any]:
    if size_id not in SIZE_PRESETS:
        valid = ", ".join(SIZE_PRESETS.keys())
        raise KeyError(f"Unknown size_preset {size_id!r}. Valid options: {valid}")
    return SIZE_PRESETS[size_id]


def get_taste_spec(taste_id: str) -> dict[str, Any]:
    if taste_id not in TASTE_PRESETS:
        valid = ", ".join(TASTE_PRESETS.keys())
        raise KeyError(f"Unknown taste_preset {taste_id!r}. Valid options: {valid}")
    return TASTE_PRESETS[taste_id]


def get_blueprint(size_id: str, taste_id: str, direction: str = "down") -> str:
    key = (size_id, taste_id, direction)
    if key not in BLUEPRINTS:
        avail = [f"{s}/{t}/{d}" for (s, t, d) in BLUEPRINTS.keys()]
        raise KeyError(f"Blueprint {key} not found. Available: {', '.join(avail)}")
    return textwrap.dedent(BLUEPRINTS[key]).strip("\n")


def main() -> int:
    parser = argparse.ArgumentParser(description="サイズ規格 × デザインテイスト別の素体ブループリント参照ツール")
    parser.add_argument("--list", action="store_true", help="利用可能なサイズ規格・テイスト・素体一覧を表示")
    parser.add_argument("--info", nargs=2, metavar=("SIZE_ID", "TASTE_ID"), help="指定したサイズ×テイストの定量仕様を表示")
    parser.add_argument("--show", nargs=3, metavar=("SIZE_ID", "TASTE_ID", "DIR"), help="指定した素体ASCIIマップを表示")
    args = parser.parse_args()

    if args.list:
        print("=== Size Presets ===")
        for k, v in SIZE_PRESETS.items():
            print(f"  - {k:12s}: {v['label']} (canvas={v['canvas_size']}, body_h={v['body_height_range']}px)")
        print("\n=== Taste Presets ===")
        for k, v in TASTE_PRESETS.items():
            print(f"  - {k:14s}: {v['label']}")
        print("\n=== Available Verified Blueprints ===")
        for s, t, d in BLUEPRINTS:
            print(f"  - {s} / {t} / {d}")
        return 0

    if args.info:
        s_id, t_id = args.info
        out = {
            "size_preset": {s_id: get_size_spec(s_id)},
            "taste_preset": {t_id: get_taste_spec(t_id)},
        }
        print(json.dumps(out, ensure_ascii=False, indent=2))
        return 0

    if args.show:
        s_id, t_id, d_id = args.show
        bp = get_blueprint(s_id, t_id, d_id)
        lines = bp.splitlines()
        print(f"# Blueprint: {s_id} x {t_id} ({d_id}) — {len(lines[0])}x{len(lines)} px")
        print(bp)
        return 0

    parser.print_help()
    return 0


if __name__ == "__main__":
    sys.exit(main())
